/**
 * Guards `public/` against accidentally publishing source material.
 *
 *   node scripts/check-public-assets.mjs
 *
 * WHY THIS EXISTS
 *
 * Next.js serves everything under `public/` verbatim, so a file dropped there
 * is live on the internet the moment it deploys — no import, no reference, no
 * link required. On 2026-09-08 `public/assets/` briefly held a screenshot of a
 * logged-in production dispatch console containing named EU customers, full
 * street addresses, phone numbers and per-order values. It was caught before it
 * was committed. It would have been served at `/assets/<name>.png` and indexed.
 *
 * The failure mode is not carelessness, it is that `public/` looks like a
 * scratch folder and behaves like a web root. So the rule is explicit: every
 * file under `public/` is an intentional publication and must be listed here.
 *
 * Raw source material — unprocessed screenshots, original portraits, reference
 * captures — belongs in `design/source/`, which is gitignored and never served.
 */
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const PUBLIC_DIR = path.join(process.cwd(), "public");

/**
 * Every file intended to be publicly served, as a POSIX path relative to
 * `public/`. Adding a file here is the act of deciding to publish it — do that
 * deliberately, and only after looking at what the file actually contains.
 */
const ALLOWLIST = new Set([
  "og.png", // social card, generated by scripts/generate-brand-assets.mjs
  "assets/VanAnhQuan_FrontendDeveloper.pdf", // the CV, public by intent (2026-09-08)
  // Project imagery, built by scripts/prepare-project-media.mjs. The provenance
  // of each source, and the personal-data audit behind publishing it, are
  // documented in that script's header. Read it before adding a row here.
  "media/panda-erp-pos-order-entry.webp",
  "media/panda-erp-pos-tables.webp",
  "media/panda-erp-kds.webp",
  "media/panda-erp-mobile-dashboard.webp",
  "media/skyline-home.webp",
  "media/skyline-feature-picker.webp",
  "media/skyline-login.webp",
  "media/tamda-dispatch.webp",
  "media/comzone-01.webp",
  "media/portrait.png", // cut out by scripts/prepare-portrait.mjs
  // Next.js starter SVGs. Unused by any component; kept only because removing
  // them is unrelated churn. Safe to delete.
  "file.svg",
  "globe.svg",
  "next.svg",
  "vercel.svg",
  "window.svg",
]);

async function walk(dir, base = "") {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files.push(...(await walk(path.join(dir, entry.name), rel)));
    } else {
      files.push(rel);
    }
  }
  return files;
}

const found = await walk(PUBLIC_DIR);

const unexpected = found.filter((file) => !ALLOWLIST.has(file));
const missing = [...ALLOWLIST].filter((file) => !found.includes(file));

if (unexpected.length > 0) {
  console.error(
    `\npublic/ contains ${unexpected.length} file${unexpected.length === 1 ? "" : "s"} ` +
      `that ${unexpected.length === 1 ? "is" : "are"} not allowlisted:\n\n` +
      unexpected.map((f) => `  public/${f}`).join("\n") +
      `\n\nEverything under public/ is served at https://<domain>/<path> with no\n` +
      `link required. Before allowlisting a file in scripts/check-public-assets.mjs,\n` +
      `open it and confirm it contains nothing private — customer names, addresses,\n` +
      `phone numbers, internal URLs, logged-in sessions, or anyone else's data.\n` +
      `Raw source material goes in design/source/ instead.\n`,
  );
  process.exit(1);
}

if (missing.length > 0) {
  console.error(
    `\nscripts/check-public-assets.mjs allowlists ${missing.length} file${
      missing.length === 1 ? "" : "s"
    } that no longer exist:\n\n` +
      missing.map((f) => `  public/${f}`).join("\n") +
      `\n\nIf ${missing.length === 1 ? "it was" : "they were"} removed on purpose, drop ` +
      `${missing.length === 1 ? "it" : "them"} from the allowlist.\n` +
      `The CV entry failing here means the download link in the contact footer is dead.\n`,
  );
  process.exit(1);
}

console.log(`public/ OK — ${found.length} files, all allowlisted`);
